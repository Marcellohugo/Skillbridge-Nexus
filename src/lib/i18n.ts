export type I18nFormatters = ReturnType<typeof createI18nFormatters>;

export function isLocale(value: unknown): value is Locale {
  return typeof value === "string" && (LOCALES as readonly string[]).includes(value);
}

export function resolveLocale(value: unknown, fallback: Locale = DEFAULT_LOCALE): Locale {
  return isLocale(value) ? value : fallback;
}

export function translate(locale: Locale, key: TranslationKey): string {
  return dictionary[locale]?.[key] ?? dictionary[DEFAULT_LOCALE][key] ?? key;
}

export function formatDate(value: Date | number | string, locale: Locale = DEFAULT_LOCALE, options?: Intl.DateTimeFormatOptions): string {
  return new Intl.DateTimeFormat(LOCALE_TAGS[locale], options).format(new Date(value));
}

export function formatDateTime(value: Date | number | string, locale: Locale = DEFAULT_LOCALE, options?: Intl.DateTimeFormatOptions): string {
  return formatDate(value, locale, {
    dateStyle: "medium",
    timeStyle: "short",
    ...options,
  });
}

export function formatNumber(value: number, locale: Locale = DEFAULT_LOCALE, options?: Intl.NumberFormatOptions): string {
  return new Intl.NumberFormat(LOCALE_TAGS[locale], options).format(value);
}

export function formatCurrency(
  value: number,
  locale: Locale = DEFAULT_LOCALE,
  currency = DEFAULT_CURRENCY[locale],
  options?: Intl.NumberFormatOptions,
): string {
  return new Intl.NumberFormat(LOCALE_TAGS[locale], {
    style: "currency",
    currency,
    maximumFractionDigits: currency === "IDR" ? 0 : 2,
    ...options,
  }).format(value);
}

export function formatRelativeTime(
  value: number,
  unit: Intl.RelativeTimeFormatUnit,
  locale: Locale = DEFAULT_LOCALE,
  options?: Intl.RelativeTimeFormatOptions,
): string {
  return new Intl.RelativeTimeFormat(LOCALE_TAGS[locale], {
    numeric: "always",
    ...options,
  }).format(value, unit);
}

export function createI18nFormatters(locale: Locale) {
  return {
    locale,
    date: (value: Date | number | string, options?: Intl.DateTimeFormatOptions) => formatDate(value, locale, options),
    dateTime: (value: Date | number | string, options?: Intl.DateTimeFormatOptions) => formatDateTime(value, locale, options),
    number: (value: number, options?: Intl.NumberFormatOptions) => formatNumber(value, locale, options),
    currency: (value: number, currency?: string, options?: Intl.NumberFormatOptions) => formatCurrency(value, locale, currency, options),
    relativeTime: (value: number, unit: Intl.RelativeTimeFormatUnit, options?: Intl.RelativeTimeFormatOptions) =>
      formatRelativeTime(value, unit, locale, options),
  };
}
